#!/usr/bin/env python3
"""column_shapes — how a query's cost scales with the COLUMNS it touches, and
what shape of per-row arithmetic it does.

Two sweeps at fixed N (50,000 rows, L2-resident at every k tested):

  RMW   `e.p_i: e.p_i + e.v_i` for i in 1..k  — 2k column reads, k column
        writes, k INDEPENDENT add chains. This is the simple_iter shape.
  FOLD  `check.sum: check.sum + e.p_1 + e.v_1 + ...` — 2k column reads, no
        column write, and ONE SERIAL dependency chain through the accumulator.

WHY. The board's iteration scaling probe found that f32 sustains a lower byte
rate than f64 on instruction-identical loops. The first hypothesis was the
addressing mode (f32's loop walked six post-incremented pointers where f64's
used one base register with register offsets). This probe kills that: from
k=4 upward BOTH widths emit register-offset addressing and the deficit is
unchanged. It also plateaus rather than growing with pointer count. So the
f32/f64 asymmetry is real, stable, and NOT addressing. It remains open.

What the probe found instead is larger, and it is about shape rather than
width: a FOLD runs at exactly one FP-add latency per element and is 8-12x
slower than an RMW over the same columns. That is the cost a declared
reduction (log-depth tree, or simply several accumulators) would remove.

    python3 probes/column_shapes.py [--runs N] [--json out.json]
"""
import argparse, json, os, shutil, statistics, subprocess, sys, tempfile, time
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KORUC = os.environ.get("KORUC", "/usr/local/bin/koruc")
if not os.access(KORUC, os.X_OK):
    KORUC = os.path.join(ROOT, "../../../koru/zig-out/bin/koruc")

ROWS = 50000
KS = [1, 2, 3, 4, 5, 6, 8]
FOLD_KS = [3, 8]
WIDTH = {"f32": 4, "f64": 8}
BANG = chr(33)

HEAD = """// GENERATED by probes/column_shapes.py — edit the generator, never this file.
// {title}
import std/io
import std/store
import std/time

std/store:new(ents, capacity: {n}) {{ {cols} }}
std/store:new(check) {{ sum: 0.0[f64] }}
std/store:new(out) {{ v: 0.0[f64] }}

std/store:watch(out)
{B} v x |> std/io:print.ln("checksum {{{{ x:f }}}}")

for(0..{n})
{B} each _ |> std/store:insert(ents) {{ {init} }}
"""

RMW_TAIL = """
for(0..100)
{B} each _ |> std/store:query(ents)
    {B} query e |> std/store:stored {{ {adv} }}

std/time:now(): start |> for(0..1000)
{B} each _ |> std/store:query(ents)
    {B} query e |> std/store:stored {{ {adv} }}
| done |> std/time:elapsed(start): d |> std/io:print.ln("total_ns {{{{ d.ns:d }}}}") |> std/io:print.ln("timed_iters 1000")

std/store:query(ents)
{B} query e |> std/store:stored {{ check.sum: check.sum{fold} }}

std/store:stored {{ out.v: check.sum }}
"""

FOLD_TAIL = """
for(0..100)
{B} each _ |> std/store:query(ents)
    {B} query e |> std/store:stored {{ check.sum: check.sum{fold} }}

std/store:stored {{ check.sum: 0.0 }}
std/time:now(): start |> for(0..1000)
{B} each _ |> std/store:query(ents)
    {B} query e |> std/store:stored {{ check.sum: check.sum{fold} }}
| done |> std/time:elapsed(start): d |> std/io:print.ln("total_ns {{{{ d.ns:d }}}}") |> std/io:print.ln("timed_iters 1000")

std/store:stored {{ out.v: check.sum }}
"""


def specs():
    out = []
    for ty in ("f32", "f64"):
        for k in KS:
            cols = ", ".join(f"p{i}: {ty}" for i in range(1, k + 1)) + ", " + \
                   ", ".join(f"v{i}: {ty}" for i in range(1, k + 1))
            head = dict(n=ROWS, cols=cols, B=BANG)
            # RMW: p_i starts 0, v_i is 1; 1100 passes leave p_i = 1100.
            init = ", ".join(f"p{i}: 0.0" for i in range(1, k + 1)) + ", " + \
                   ", ".join(f"v{i}: 1.0" for i in range(1, k + 1))
            src = HEAD.format(title=f"RMW k={k} {ty}: e.p_i += e.v_i for i in 1..{k}",
                              init=init, **head) + \
                RMW_TAIL.format(B=BANG,
                                adv=", ".join(f"e.p{i}: e.p{i} + e.v{i}" for i in range(1, k + 1)),
                                fold="".join(f" + e.p{i}" for i in range(1, k + 1)))
            out.append(dict(name=f"rmw_{ty}_k{k}", kind="rmw", width=ty, k=k, src=src,
                            oracle=f"checksum {ROWS * 1100 * k}",
                            bytes_per_pass=ROWS * WIDTH[ty] * 3 * k))
        for k in FOLD_KS:
            cols = ", ".join(f"p{i}: {ty}" for i in range(1, k + 1)) + ", " + \
                   ", ".join(f"v{i}: {ty}" for i in range(1, k + 1))
            # FOLD: every column holds 1.0; the accumulator is zeroed after warmup,
            # so 1000 timed passes each add 2k per row.
            init = ", ".join(f"p{i}: 1.0" for i in range(1, k + 1)) + ", " + \
                   ", ".join(f"v{i}: 1.0" for i in range(1, k + 1))
            src = HEAD.format(title=f"FOLD k={k} {ty}: serial accumulate of {2*k} columns per row",
                              init=init, n=ROWS, cols=cols, B=BANG) + \
                FOLD_TAIL.format(B=BANG,
                                 fold="".join(f" + e.p{i} + e.v{i}" for i in range(1, k + 1)))
            out.append(dict(name=f"fold_{ty}_k{k}", kind="fold", width=ty, k=k, src=src,
                            oracle=f"checksum {ROWS * 2 * k * 1000}",
                            bytes_per_pass=ROWS * WIDTH[ty] * 2 * k,
                            dependent_adds_per_pass=ROWS * 2 * k))
    return out


def build(sp, base):
    d = os.path.join(base, sp["name"])
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "prog.k"), "w") as f:
        f.write(sp["src"])
    cp = subprocess.run([KORUC, "build", "prog.k"], cwd=d, capture_output=True, text=True, timeout=1800)
    ok = cp.returncode == 0 and os.path.exists(os.path.join(d, "a.out"))
    return sp["name"], ok, ("" if ok else (cp.stdout + cp.stderr)[-400:])


def addressing(path):
    """Report the emitted hot loop's addressing form: post-incremented pointers
    versus one base register plus register offsets."""
    import re
    dd = subprocess.run(["objdump", "-d", "--no-show-raw-insn", path],
                        capture_output=True, text=True).stdout.split("\n")
    hit = [i for i, l in enumerate(dd) if re.search(r"fadd\.(4s|2d)", l)]
    if not hit:
        return dict(form="none-vector", post_inc=0, reg_offset=0)
    seg = "\n".join(dd[max(0, min(hit) - 6): max(hit) + 8])
    post = len(re.findall(r"\], #0x10", seg))
    reg = len(re.findall(r"\[x\d+, x\d+\]", seg))
    return dict(form="post-inc" if post > reg else "reg-offset", post_inc=post, reg_offset=reg)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=9)
    ap.add_argument("--json", default=os.path.join(ROOT, "results", "column-shapes.json"))
    args = ap.parse_args()

    sps = specs()
    base = tempfile.mkdtemp(prefix="colshapes-")
    print(f"koruc: {KORUC}\nbuilding {len(sps)} ports")
    t0 = time.time()
    with ThreadPoolExecutor(max_workers=3) as ex:
        built = list(ex.map(lambda s: build(s, base), sps))
    bad = [b for b in built if not b[1]]
    print(f"  compiled {len(built) - len(bad)}/{len(built)} in {time.time() - t0:.0f}s")
    for b in bad:
        print(f"  BLOCKED {b[0]}: {b[2][:200]}", file=sys.stderr)
    if bad:
        sys.exit(1)

    print(subprocess.run(["uptime"], capture_output=True, text=True).stdout.strip())
    samples = {s["name"]: [] for s in sps}
    for _ in range(args.runs):
        for sp in sps:
            d = os.path.join(base, sp["name"])
            out = subprocess.run([os.path.join(d, "a.out")], cwd=d,
                                 capture_output=True, text=True, timeout=1800).stdout
            chk = "\n".join(l for l in out.splitlines() if l.startswith("checksum "))
            if chk.rstrip() != sp["oracle"]:
                print(f"WRONG ANSWER {sp['name']}: got {chk!r} want {sp['oracle']!r}", file=sys.stderr)
                sys.exit(1)
            tot = sum(int(l.split()[1]) for l in out.splitlines() if l.startswith("total_ns "))
            it = int(next(l for l in out.splitlines() if l.startswith("timed_iters ")).split()[1])
            samples[sp["name"]].append(tot / it)
    print(subprocess.run(["uptime"], capture_output=True, text=True).stdout.strip())

    res = {}
    for sp in sps:
        xs = samples[sp["name"]]
        med = statistics.median(xs)
        e = dict(kind=sp["kind"], width=sp["width"], columns=sp["k"],
                 median_ns=round(med), min_ns=round(min(xs)),
                 bytes_per_pass=sp["bytes_per_pass"],
                 gb_per_s=round(sp["bytes_per_pass"] / med, 1))
        if sp["kind"] == "rmw":
            e["addressing"] = addressing(os.path.join(base, sp["name"], "a.out"))
        else:
            e["dependent_adds_per_pass"] = sp["dependent_adds_per_pass"]
            e["ns_per_dependent_add"] = round(med / sp["dependent_adds_per_pass"], 4)
        res[sp["name"]] = e

    print(f"\n=== RMW: e.p_i += e.v_i, N={ROWS}")
    print(f"{'k':>3}{'f32 ns':>10}{'f64 ns':>10}{'f32 GB/s':>10}{'f64 GB/s':>10}{'f32/f64':>9}  addressing f32 / f64")
    for k in KS:
        a, b = res[f"rmw_f32_k{k}"], res[f"rmw_f64_k{k}"]
        print(f"{k:>3}{a['median_ns']:>10}{b['median_ns']:>10}{a['gb_per_s']:>10}{b['gb_per_s']:>10}"
              f"{a['gb_per_s']/b['gb_per_s']*100:>8.1f}%  {a['addressing']['form']} / {b['addressing']['form']}")

    print(f"\n=== FOLD: check.sum += 2k columns per row (ONE serial chain), N={ROWS}")
    print(f"{'k':>3}{'width':>7}{'ns':>10}{'dep adds':>11}{'ns/add':>9}{'cyc/add @3.5GHz':>17}{'vs RMW':>9}")
    for k in FOLD_KS:
        for ty in ("f32", "f64"):
            f = res[f"fold_{ty}_k{k}"]
            print(f"{k:>3}{ty:>7}{f['median_ns']:>10}{f['dependent_adds_per_pass']:>11}"
                  f"{f['ns_per_dependent_add']:>9.3f}{f['ns_per_dependent_add']*3.5:>17.2f}"
                  f"{f['median_ns']/res[f'rmw_{ty}_k{k}']['median_ns']:>8.1f}x")

    koruc_real = os.path.realpath(KORUC)
    commit = subprocess.run(["git", "-C", os.path.dirname(koruc_real) + "/../..", "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip() or "unknown"
    doc = dict(
        suite="ecs-store", kind="koru-inprocess-probe", probe="column_shapes",
        generated_at=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        rows=ROWS,
        machine=dict(os=os.uname().sysname, arch=os.uname().machine,
                     cpu=subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"],
                                        capture_output=True, text=True).stdout.strip(),
                     load_avg=subprocess.run(["sysctl", "-n", "vm.loadavg"],
                                             capture_output=True, text=True).stdout.strip().strip("{} ")),
        koru=dict(commit=commit),
        protocol=dict(
            process_runs=args.runs,
            instrument="in-process std/time around 1000 timed passes; median across interleaved process runs",
            caveat="gb_per_s and cycles/add are DERIVED from a traffic model and a nominal 3.5 GHz, not from hardware counters. Comparable between rows of these tables and nowhere else.",
            fold_note="the FOLD series is NOT a write-free control for the RMW series — it also collapses k independent add chains into one serial chain. That confound is the finding, not a flaw to correct: it is what isolates the latency bound."),
        results=res)
    with open(args.json, "w") as f:
        json.dump(doc, f, indent=2)
        f.write("\n")
    print(f"\nPersisted: {args.json}")


if __name__ == "__main__":
    main()
