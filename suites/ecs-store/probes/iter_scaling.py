#!/usr/bin/env python3
"""iter_scaling — slide simple_iter's timed loop through the cache hierarchy.

WHY THIS EXISTS. The board's `simple_iter` family is measured at one row count
(10,000) and two widths, and a ratio taken across those four points produced a
finding that turned out to be an ARTIFACT: `simple_iter_1col_f32` has an 80 KB
read set and is L1-resident, while every other port in the family spills to L2.
Comparing them as if they shared a memory regime manufactured a defect that was
not there. This probe exists so that comparison can never be made blind again —
it sweeps N so every claim can be read at MATCHED cache residency.

WHAT IT MEASURES. The same workload as `koru/simple_iter/`: N rows, six columns
(px py pz vx vy vz), advancing 1 or 3 position columns per pass. Four series
(f32/f64 x 1col/3col) at N in 1250..250000, so the read set sweeps 9 KB (deep
L1) to 11.7 MB (deep L2). Protocol matches the board's ports exactly: 100
untimed warmup passes, 1000 timed passes bracketed by std/time, checksum-gated
against N * 1100 * ncol. The N=10000 points are CONTROLS — they must reproduce
the published board, and they do, within 2.1%.

NOT A BOARD ENTRY. These 32 ports deliberately live outside `koru/`, so
`bench-inprocess.sh` does not discover them and the published board's interleave
set stays fixed. Run this directly when a question about scaling comes up.

    python3 probes/iter_scaling.py [--runs N] [--json out.json]
"""
import argparse, glob, json, os, shutil, statistics, subprocess, sys, tempfile, time
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KORUC = os.environ.get("KORUC", "/usr/local/bin/koruc")
if not os.access(KORUC, os.X_OK):
    KORUC = os.path.join(ROOT, "../../../koru/zig-out/bin/koruc")

NS = [1250, 2500, 5000, 10000, 20000, 50000, 100000, 250000]
AXES = ["x", "y", "z"]
WIDTH = {"f32": 4, "f64": 8}
BANG = chr(33)

TPL = """// iter_scaling {name} — simple_iter's timed loop at N={n} rows, {ty} columns,
// advancing {ncol} position column(s) per row. GENERATED by
// probes/iter_scaling.py; edit the generator, never this file.
//
// Protocol is byte-for-byte the board's: 100 untimed warmup passes, 1000 timed
// passes bracketed by std/time, checksum = N x 1100 x {ncol} accumulated in f64
// (an f32 column widens losslessly; every partial sum is an exact integer).
import std/io
import std/store
import std/time

std/store:new(ents, capacity: {n}) {{ {cols} }}
std/store:new(check) {{ sum: 0.0[f64] }}
std/store:new(out) {{ v: 0.0[f64] }}

std/store:watch(out)
{B} v x |> std/io:print.ln("checksum {{{{ x:f }}}}")

for(0..{n})
{B} each _ |> std/store:insert(ents) {{ {init} }}

for(0..100)
{B} each _ |> std/store:query(ents)
    {B} query e |> std/store:stored {{ {advance} }}

std/time:now(): start |> for(0..1000)
{B} each _ |> std/store:query(ents)
    {B} query e |> std/store:stored {{ {advance} }}
| done |> std/time:elapsed(start): d |> std/io:print.ln("total_ns {{{{ d.ns:d }}}}") |> std/io:print.ln("timed_iters 1000")

std/store:query(ents)
{B} query e |> std/store:stored {{ check.sum: check.sum{fold} }}

std/store:stored {{ out.v: check.sum }}
"""


def specs():
    out = []
    for ty in ("f32", "f64"):
        for ncol in (1, 3):
            for n in NS:
                cols = ", ".join(f"p{a}: {ty}" for a in AXES) + ", " + ", ".join(f"v{a}: {ty}" for a in AXES)
                init = ", ".join(f"p{a}: 0.0" for a in AXES) + ", " + ", ".join(f"v{a}: 1.0" for a in AXES)
                out.append(dict(
                    name=f"is_{ty}_{ncol}col_{n}", ty=ty, ncol=ncol, n=n,
                    oracle=f"checksum {n * 1100 * ncol}",
                    src=TPL.format(name=f"is_{ty}_{ncol}col_{n}", n=n, ty=ty, ncol=ncol, cols=cols,
                                   init=init, B=BANG,
                                   advance=", ".join(f"e.p{a}: e.p{a} + e.v{a}" for a in AXES[:ncol]),
                                   fold="".join(f" + e.p{a}" for a in AXES[:ncol]))))
    return out


def build(sp, base):
    d = os.path.join(base, sp["name"])
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "prog.k"), "w") as f:
        f.write(sp["src"])
    cp = subprocess.run([KORUC, "build", "prog.k"], cwd=d, capture_output=True, text=True, timeout=1800)
    ok = cp.returncode == 0 and os.path.exists(os.path.join(d, "a.out"))
    return sp["name"], ok, ("" if ok else (cp.stdout + cp.stderr)[-400:])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=9)
    ap.add_argument("--json", default=os.path.join(ROOT, "results", "iter-scaling.json"))
    args = ap.parse_args()

    sps = specs()
    base = tempfile.mkdtemp(prefix="iter-scaling-")
    print(f"koruc: {KORUC}\nbuilding {len(sps)} ports in {base}")
    t0 = time.time()
    with ThreadPoolExecutor(max_workers=3) as ex:
        built = list(ex.map(lambda s: build(s, base), sps))
    bad = [b for b in built if not b[1]]
    print(f"  compiled {len(built) - len(bad)}/{len(built)} in {time.time() - t0:.0f}s")
    for b in bad:
        print(f"  BLOCKED {b[0]}: {b[2][:200]}", file=sys.stderr)
    if bad:
        sys.exit(1)

    # Interleaved: round 1 of every port, round 2 of every port, ... so every
    # repetition index shares whatever load exists at that moment.
    print(subprocess.run(["uptime"], capture_output=True, text=True).stdout.strip())
    samples = {s["name"]: [] for s in sps}
    for _ in range(args.runs):
        for sp in sps:
            d = os.path.join(base, sp["name"])
            out = subprocess.run([os.path.join(d, "a.out")], cwd=d,
                                 capture_output=True, text=True, timeout=1800).stdout
            chk = "\n".join(l for l in out.splitlines() if l.startswith("checksum "))
            if chk.rstrip() != sp["oracle"]:
                print(f"WRONG ANSWER {sp['name']}: got {chk!r} want {sp['oracle']!r}", file=sys.stderr)
                sys.exit(1)
            tot = sum(int(l.split()[1]) for l in out.splitlines() if l.startswith("total_ns "))
            it = int(next(l for l in out.splitlines() if l.startswith("timed_iters ")).split()[1])
            samples[sp["name"]].append(tot / it)
    print(subprocess.run(["uptime"], capture_output=True, text=True).stdout.strip())

    res = {}
    for sp in sps:
        xs = samples[sp["name"]]
        traffic = sp["n"] * WIDTH[sp["ty"]] * 3 * sp["ncol"]   # ncol p-reads + v-reads + p-writes
        readset = sp["n"] * WIDTH[sp["ty"]] * 2 * sp["ncol"]
        med = statistics.median(xs)
        res[sp["name"]] = dict(width=sp["ty"], columns=sp["ncol"], rows=sp["n"],
                               median_ns=round(med), min_ns=round(min(xs)),
                               bytes_per_pass=traffic, read_set_bytes=readset,
                               gb_per_s=round(traffic / med, 1),
                               ns_per_vector_iter=round(med / (sp["n"] / (16 // WIDTH[sp["ty"]])), 3))

    for ncol in (1, 3):
        print(f"\n=== {ncol}-column     (L1d 128 KB · L2 16 MB shared)")
        print(f"{'N':>8} | {'f32 ns':>9}{'GB/s':>8}{'rset':>9} | {'f64 ns':>9}{'GB/s':>8}{'rset':>9}")
        for n in NS:
            a = res[f"is_f32_{ncol}col_{n}"]
            b = res[f"is_f64_{ncol}col_{n}"]
            print(f"{n:>8} | {a['median_ns']:>9}{a['gb_per_s']:>8}{a['read_set_bytes']//1024:>8}K"
                  f" | {b['median_ns']:>9}{b['gb_per_s']:>8}{b['read_set_bytes']//1024:>8}K")

    koruc_real = os.path.realpath(KORUC)
    commit = subprocess.run(["git", "-C", os.path.dirname(koruc_real) + "/../..", "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip() or "unknown"
    doc = dict(
        suite="ecs-store", kind="koru-inprocess-probe", probe="iter_scaling",
        generated_at=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        machine=dict(os=os.uname().sysname, arch=os.uname().machine,
                     cpu=subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"],
                                        capture_output=True, text=True).stdout.strip(),
                     load_avg=subprocess.run(["sysctl", "-n", "vm.loadavg"],
                                             capture_output=True, text=True).stdout.strip().strip("{} ")),
        koru=dict(commit=commit),
        protocol=dict(
            process_runs=args.runs,
            instrument="in-process std/time around 1000 timed passes; per-pass ns = total_ns/timed_iters; median across interleaved process runs",
            controls="the N=10000 points reproduce koru/simple_iter/'s published board figures; they are the generator's correctness check",
            traffic_model="bytes_per_pass = rows * width * 3 * columns (ncol position reads + ncol velocity reads + ncol position writes); read_set_bytes omits the write-back",
            caveat="gb_per_s is a DERIVED figure from the traffic model above, not a hardware counter. It is comparable BETWEEN rows of this table and nowhere else."),
        results=res)
    with open(args.json, "w") as f:
        json.dump(doc, f, indent=2)
        f.write("\n")
    print(f"\nPersisted: {args.json}")


if __name__ == "__main__":
    main()
