#!/usr/bin/env python3
"""read_ladder — hold the WRITES fixed, vary the READS, and watch what happens
to the width dividend and to the absolute cost.

Three per-row shapes over one store of k position and k velocity columns.
Writes are k in every shape; reads go 0 -> k -> 2k:

  write   e.p_i: <const>          0 reads,  k writes
  copy    e.p_i: e.v_i            k reads,  k writes
  rmw     e.p_i: e.p_i + e.v_i    2k reads, k writes

Run at f32/f64 AND i32/i64, so "is this a float property?" gets an answer
rather than an assumption. Then the three shapes are re-run at a row count
whose whole store fits in L1, which is what turns the headline result from an
anomaly into a mechanism.

WHY. Earlier probes found f32 sustaining a lower byte rate than f64 on
instruction-identical loops, and could not explain it. iter_scaling ruled out
vectorization and unrolling; column_shapes ruled out the addressing mode. The
remaining lead came from the boundary entries: a pure streaming write narrowed
at ~1.89x where a read-modify-write narrowed at ~1.5x, hinting the deficit
sits on the READ path. This probe tests that directly, and finds something
sharper on the way.

    python3 probes/read_ladder.py [--runs N] [--json out.json]
"""
import argparse, json, os, shutil, statistics, subprocess, sys, tempfile, time
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KORUC = os.environ.get("KORUC", "/usr/local/bin/koruc")
if not os.access(KORUC, os.X_OK):
    KORUC = os.path.join(ROOT, "../../../koru/zig-out/bin/koruc")

BIG_N, SMALL_N, K = 50000, 2000, 3
WIDTH = {"f32": 4, "f64": 8, "i32": 4, "i64": 8}
BANG = chr(33)

TPL = """// GENERATED by probes/read_ladder.py — {shape} {ty} k={k} N={n}.
// Writes are held fixed at k per row; reads are {reads} per row.
import std/io
import std/store
import std/time

std/store:new(ents, capacity: {n}) {{ {cols} }}
std/store:new(check) {{ sum: {zero}[{acc}] }}
std/store:new(out) {{ v: {zero}[{acc}] }}

std/store:watch(out)
{B} v x |> std/io:print.ln("checksum {{{{ x:{fmt} }}}}")

for(0..{n})
{B} each _ |> std/store:insert(ents) {{ {init} }}

for(0..100)
{B} each _ |> std/store:query(ents)
    {B} query e |> std/store:stored {{ {body} }}

std/time:now(): start |> for(0..1000)
{B} each _ |> std/store:query(ents)
    {B} query e |> std/store:stored {{ {body} }}
| done |> std/time:elapsed(start): d |> std/io:print.ln("total_ns {{{{ d.ns:d }}}}") |> std/io:print.ln("timed_iters 1000")

std/store:query(ents)
{B} query e |> std/store:stored {{ check.sum: check.sum{fold} }}

std/store:stored {{ out.v: check.sum }}
"""


def make(ty, n, k=K):
    """Yield the three shapes for one type at one row count."""
    isf = ty[0] == "f"
    one, zero, acc, fmt = ("1.0", "0.0", "f64", "f") if isf else ("1", "0", "i64", "d")
    cols = ", ".join(f"p{i}: {ty}" for i in range(1, k + 1)) + ", " + \
           ", ".join(f"v{i}: {ty}" for i in range(1, k + 1))
    init = ", ".join(f"p{i}: {zero}" for i in range(1, k + 1)) + ", " + \
           ", ".join(f"v{i}: {one}" for i in range(1, k + 1))
    fold = "".join(f" + e.p{i}" for i in range(1, k + 1))
    shapes = (
        # (name, per-row body, reads/row, checksum total)
        ("write", ", ".join(f"e.p{i}: {one}"           for i in range(1, k + 1)), 0,     n * k),
        ("copy",  ", ".join(f"e.p{i}: e.v{i}"          for i in range(1, k + 1)), k,     n * k),
        ("rmw",   ", ".join(f"e.p{i}: e.p{i} + e.v{i}" for i in range(1, k + 1)), 2 * k, n * k * 1100),
    )
    for shape, body, reads, total in shapes:
        yield dict(
            name=f"{shape}_{ty}_{n}", shape=shape, ty=ty, rows=n, reads_per_row=reads,
            writes_per_row=k, oracle=f"checksum {total}",
            bytes_per_pass=n * WIDTH[ty] * (reads + k),
            store_bytes=n * WIDTH[ty] * 2 * k,
            src=TPL.format(shape=shape, ty=ty, k=k, n=n, cols=cols, init=init, body=body,
                           fold=fold, zero=zero, acc=acc, fmt=fmt, reads=reads, B=BANG))


def specs():
    out = []
    for ty in ("f32", "f64", "i32", "i64"):
        out += list(make(ty, BIG_N))
    out += list(make("f64", SMALL_N))          # the L1-resident control
    return out


def build(sp, base):
    d = os.path.join(base, sp["name"])
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "prog.k"), "w") as f:
        f.write(sp["src"])
    cp = subprocess.run([KORUC, "build", "prog.k"], cwd=d, capture_output=True, text=True, timeout=1800)
    ok = cp.returncode == 0 and os.path.exists(os.path.join(d, "a.out"))
    return sp["name"], ok, ("" if ok else (cp.stdout + cp.stderr)[-400:])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=11)
    ap.add_argument("--json", default=os.path.join(ROOT, "results", "read-ladder.json"))
    args = ap.parse_args()

    sps = specs()
    base = tempfile.mkdtemp(prefix="readladder-")
    print(f"koruc: {KORUC}\nbuilding {len(sps)} ports")
    t0 = time.time()
    with ThreadPoolExecutor(max_workers=3) as ex:
        built = list(ex.map(lambda s: build(s, base), sps))
    bad = [b for b in built if not b[1]]
    print(f"  compiled {len(built) - len(bad)}/{len(built)} in {time.time() - t0:.0f}s")
    for b in bad:
        print(f"  BLOCKED {b[0]}: {b[2][:200]}", file=sys.stderr)
    if bad:
        sys.exit(1)

    print(subprocess.run(["uptime"], capture_output=True, text=True).stdout.strip())
    samples = {s["name"]: [] for s in sps}
    for _ in range(args.runs):
        for sp in sps:
            d = os.path.join(base, sp["name"])
            out = subprocess.run([os.path.join(d, "a.out")], cwd=d,
                                 capture_output=True, text=True, timeout=1800).stdout
            chk = "\n".join(l for l in out.splitlines() if l.startswith("checksum "))
            if chk.rstrip() != sp["oracle"]:
                print(f"WRONG ANSWER {sp['name']}: got {chk!r} want {sp['oracle']!r}", file=sys.stderr)
                sys.exit(1)
            tot = sum(int(l.split()[1]) for l in out.splitlines() if l.startswith("total_ns "))
            it = int(next(l for l in out.splitlines() if l.startswith("timed_iters ")).split()[1])
            samples[sp["name"]].append(tot / it)
    print(subprocess.run(["uptime"], capture_output=True, text=True).stdout.strip())

    res = {}
    for sp in sps:
        xs = samples[sp["name"]]
        med = statistics.median(xs)
        res[sp["name"]] = dict(
            shape=sp["shape"], width=sp["ty"], rows=sp["rows"],
            reads_per_row=sp["reads_per_row"], writes_per_row=sp["writes_per_row"],
            median_ns=round(med), min_ns=round(min(xs)),
            ns_per_row=round(med / sp["rows"], 4),
            bytes_per_pass=sp["bytes_per_pass"], store_bytes=sp["store_bytes"],
            gb_per_s=round(sp["bytes_per_pass"] / med, 1))

    print(f"\n=== the ladder at N={BIG_N} (store spills L1 at every width)")
    print(f"{'shape':<7}{'reads/row':>10}{'f64 ns':>10}{'f32 ns':>10}{'f64/f32':>9}"
          f"{'i64 ns':>10}{'i32 ns':>10}{'i64/i32':>9}")
    for shape in ("write", "copy", "rmw"):
        g = lambda t: res[f"{shape}_{t}_{BIG_N}"]["median_ns"]
        print(f"{shape:<7}{res[f'{shape}_f64_{BIG_N}']['reads_per_row']:>10}"
              f"{g('f64'):>10}{g('f32'):>10}{g('f64')/g('f32'):>8.2f}x"
              f"{g('i64'):>10}{g('i32'):>10}{g('i64')/g('i32'):>8.2f}x")

    print(f"\n=== the same three shapes in L1 (N={SMALL_N}, f64, whole store "
          f"{res[f'write_f64_{SMALL_N}']['store_bytes']//1024} KB)")
    print(f"{'shape':<7}{'L1 ns/row':>12}{'L2 ns/row':>12}{'degradation':>13}")
    for shape in ("write", "copy", "rmw"):
        a = res[f"{shape}_f64_{SMALL_N}"]["ns_per_row"]
        b = res[f"{shape}_f64_{BIG_N}"]["ns_per_row"]
        print(f"{shape:<7}{a:>12.3f}{b:>12.3f}{b/a:>12.2f}x")

    koruc_real = os.path.realpath(KORUC)
    commit = subprocess.run(["git", "-C", os.path.dirname(koruc_real) + "/../..",
                             "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip() or "unknown"
    doc = dict(
        suite="ecs-store", kind="koru-inprocess-probe", probe="read_ladder",
        generated_at=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        machine=dict(os=os.uname().sysname, arch=os.uname().machine,
                     cpu=subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"],
                                        capture_output=True, text=True).stdout.strip(),
                     load_avg=subprocess.run(["sysctl", "-n", "vm.loadavg"],
                                             capture_output=True, text=True).stdout.strip().strip("{} ")),
        koru=dict(commit=commit),
        protocol=dict(
            process_runs=args.runs, rows_big=BIG_N, rows_small=SMALL_N, columns=K,
            instrument="in-process std/time around 1000 timed passes; median across interleaved process runs",
            oracle_note="the write and copy shapes are IDEMPOTENT, so their checksums detect the timed loop being elided but cannot count passes. The rmw shape counts passes exactly. Same limitation add_remove_component documents.",
            caveat="gb_per_s is derived from a traffic model, not a hardware counter."),
        results=res)
    with open(args.json, "w") as f:
        json.dump(doc, f, indent=2)
        f.write("\n")
    print(f"\nPersisted: {args.json}")


if __name__ == "__main__":
    main()
